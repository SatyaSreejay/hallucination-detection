"""Structured result objects shared by every pipeline stage."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any


class Label(str, Enum):
    """The three claim-level verdicts used throughout the application."""

    SUPPORTED = "SUPPORTED"
    CONTRADICTED = "CONTRADICTED"
    NOT_ENOUGH_INFORMATION = "NOT_ENOUGH_INFORMATION"


LABELS: list[str] = [label.value for label in Label]


LABEL_DISPLAY = {
    Label.SUPPORTED: "Supported",
    Label.CONTRADICTED: "Contradicted",
    Label.NOT_ENOUGH_INFORMATION: "Insufficient Evidence",
}


class Outcome(str, Enum):
    """What the user sees per claim: a verdict, or why no verdict could be made."""

    SUPPORTED = "Supported"
    CONTRADICTED = "Contradicted"
    INSUFFICIENT_EVIDENCE = "Insufficient Evidence"
    RETRIEVAL_FAILURE = "Retrieval Failure"
    VERIFICATION_ERROR = "Verification Error"


class RetrievalStatus(str, Enum):
    """Outcome of evidence retrieval for one claim."""

    OK = "OK"  # at least one passage was retrieved
    NO_RESULTS = "NO_RESULTS"  # the source answered, but nothing relevant was found
    ERROR = "ERROR"  # network/HTTP/parse failure; nothing can be concluded


@dataclass(frozen=True)
class Answer:
    """An LLM answer. Frozen so evaluation code cannot modify the original text."""

    question: str
    text: str
    model: str
    # "llm" = generated by the configured backend; "user" = pasted; "controlled-test" =
    # deliberately modified copy; "ragtruth" = dataset response
    source: str = "llm"
    provider: str = ""  # generation backend for source == "llm" (ollama, groq, ...)


@dataclass(frozen=True)
class Claim:
    """A candidate factual claim taken from an answer.

    With the default spaCy extractor a claim is one sentence (``id`` = "S3"). Sentences
    that look like they contain several assertions are flagged (``multi_assertion``), not
    decomposed. The optional LLM decomposition produces sub-claims ("S3.1", "S3.2").
    ``span_start``/``span_end`` index the source sentence in the original answer.
    """

    id: str
    text: str
    source_sentence: str
    span_start: int | None = None
    span_end: int | None = None
    extraction_method: str = "spacy"
    multi_assertion: bool = False
    flags: tuple[str, ...] = ()


@dataclass(frozen=True)
class Sentence:
    """A sentence of the original answer, in order, with its id and span.

    ``skip_reason`` is set for sentences that are not checked (questions, greetings,
    opinions, advice, fragments); they are still shown so the answer stays intact.
    """

    id: str
    text: str
    start: int
    end: int
    skip_reason: str | None = None
    multi_assertion: bool = False
    flags: tuple[str, ...] = ()


@dataclass(frozen=True)
class EvidencePassage:
    """A passage of *source* text. Never contains model-generated text."""

    title: str
    url: str
    text: str
    source: str = "wikipedia"
    page_id: int | None = None
    passage_index: int = 0
    retrieval_score: float = 0.0  # lexical-overlap rank score, not a verification score


@dataclass
class RetrievalResult:
    """Evidence retrieved for one claim, with an explicit status."""

    query: str
    status: RetrievalStatus
    passages: list[EvidencePassage] = field(default_factory=list)
    error: str | None = None
    from_cache: bool = False


@dataclass
class Verdict:
    """A verification decision for one claim.

    ``raw_scores`` holds whatever the verifier produced (e.g. NLI softmax outputs per
    passage). These are uncalibrated and must not be presented as probabilities of
    correctness. ``score_note`` explains how to read them.
    """

    label: Label
    method: str
    explanation: str
    evidence: list[EvidencePassage] = field(default_factory=list)
    raw_scores: dict[str, Any] = field(default_factory=dict)
    score_note: str = ""
    mixed_evidence: bool = False
    error: str | None = None


@dataclass
class ClaimResult:
    claim: Claim
    retrieval: RetrievalResult
    verdict: Verdict

    @property
    def outcome(self) -> Outcome:
        if self.retrieval.status is RetrievalStatus.ERROR:
            return Outcome.RETRIEVAL_FAILURE
        if self.verdict.error is not None:
            return Outcome.VERIFICATION_ERROR
        return Outcome(LABEL_DISPLAY[self.verdict.label])


@dataclass
class Summary:
    """Counts over claim results. Retrieval failures are reported separately."""

    total_claims: int
    supported: int
    contradicted: int
    not_enough_information: int
    retrieval_failures: int
    verifier_errors: int
    claims_with_evidence: int

    @property
    def contradicted_share_of_evidenced(self) -> float | None:
        """Contradicted / claims-with-evidence. Descriptive only, not a probability."""
        if self.claims_with_evidence == 0:
            return None
        return self.contradicted / self.claims_with_evidence


@dataclass
class PipelineResult:
    answer: Answer
    claims: list[ClaimResult]
    summary: Summary
    extraction_method: str
    verifier_method: str
    warnings: list[str] = field(default_factory=list)
    sentences: list[Sentence] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return _jsonable(asdict(self))


def _jsonable(obj: Any) -> Any:
    """Convert enums/paths in nested dataclass dicts to JSON-friendly values."""
    if isinstance(obj, Enum):
        return obj.value
    if isinstance(obj, dict):
        return {k: _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    return obj


def summarize(results: list[ClaimResult]) -> Summary:
    """Aggregate claim results into a :class:`Summary`."""
    return Summary(
        total_claims=len(results),
        supported=sum(r.verdict.label is Label.SUPPORTED for r in results),
        contradicted=sum(r.verdict.label is Label.CONTRADICTED for r in results),
        not_enough_information=sum(
            r.verdict.label is Label.NOT_ENOUGH_INFORMATION for r in results
        ),
        retrieval_failures=sum(r.retrieval.status is RetrievalStatus.ERROR for r in results),
        verifier_errors=sum(r.verdict.error is not None for r in results),
        claims_with_evidence=sum(r.retrieval.status is RetrievalStatus.OK for r in results),
    )
